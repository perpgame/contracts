#!/usr/bin/env node
// Reads forge build output for AgentTreasury and AgentCurve and writes
// typed TS modules to launchpad/web/src/lib/contracts/. Run after `forge build`.
//
// Usage:  node contracts/scripts/dump-artifacts.mjs
// Or from web/: npm run contracts:build

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const contractsRoot = resolve(here, "..");
const webContractsDir = resolve(contractsRoot, "../web/src/lib/contracts");

const ARTIFACTS = [
  {
    sol: "AgentTreasury.sol",
    name: "AgentTreasury",
    abiVar: "agentTreasuryAbi",
    bytecodeVar: "agentTreasuryBytecode",
  },
  {
    sol: "AgentCurve.sol",
    name: "AgentCurve",
    abiVar: "agentCurveAbi",
    bytecodeVar: "agentCurveBytecode",
  },
];

mkdirSync(webContractsDir, { recursive: true });

for (const a of ARTIFACTS) {
  const path = resolve(contractsRoot, "out", a.sol, `${a.name}.json`);
  if (!existsSync(path)) {
    console.error(`✗ Missing artifact: ${path}\n  Run \`forge build\` in launchpad/contracts first.`);
    process.exit(1);
  }
  const artifact = JSON.parse(readFileSync(path, "utf8"));
  const abi = artifact.abi;
  const bytecode = artifact.bytecode?.object;
  if (!abi || !bytecode) {
    console.error(`✗ ${a.name}: missing abi or bytecode.object in ${path}`);
    process.exit(1);
  }
  const ts =
    `// AUTO-GENERATED by contracts/scripts/dump-artifacts.mjs from forge build output.\n` +
    `// Do not edit; rerun the script after changing the Solidity.\n\n` +
    `export const ${a.abiVar} = ${JSON.stringify(abi, null, 2)} as const;\n\n` +
    `export const ${a.bytecodeVar} = "${bytecode}" as const;\n`;
  writeFileSync(resolve(webContractsDir, `${a.name}.ts`), ts);
  console.log(`✓ wrote ${a.name}.ts  (${abi.length} abi entries, ${bytecode.length / 2 - 1} bytes)`);
}
